import { FFmpeg } from '@ffmpeg/ffmpeg';
import coreURL from '@ffmpeg/core?url';


/** Lazy, single-threaded conversion. Both the engine and media stay on this origin. */
export async function convertMedia(file: File, progress: (text: string) => void, signal: AbortSignal): Promise<Blob> {
  // Input, output and the codec working set coexist in WebAssembly memory.
  if (file.size > 256 * 1024 * 1024) throw new Error('conversion is limited to 256 MB. convert this file to MP4 or MP3 first.');
  signal.throwIfAborted();
  const ffmpeg = new FFmpeg();
  const abort = () => ffmpeg.terminate();
  signal.addEventListener('abort', abort, { once: true });
  const timeout = window.setTimeout(abort, 10 * 60 * 1000);
  let wasmURL: string | undefined;
  try {
    progress('loading converter');
    // Resolve emitted chunks at runtime; these assets are generated by the build.
    const moduleURL = import.meta.url;
    const parts = await Promise.all([0, 1].map(async part => {
      const response = await fetch(new URL(`./codec/core-${part}.bin`, moduleURL), { signal });
      if (!response.ok) throw new Error('converter unavailable. reconnect and try again.');
      return response.arrayBuffer();
    }));
    signal.throwIfAborted();
    wasmURL = URL.createObjectURL(new Blob(parts, { type: 'application/wasm' }));
    await ffmpeg.load({ coreURL, wasmURL });
    signal.throwIfAborted();
    progress('converting · 0%');
    ffmpeg.on('progress', ({ progress: fraction }) => {
      if (!signal.aborted && Number.isFinite(fraction)) progress(`converting · ${Math.min(99, Math.max(0, Math.round(fraction * 100)))}%`);
    });
    const bytes = new Uint8Array(await file.arrayBuffer());
    signal.throwIfAborted();
    await ffmpeg.writeFile('input', bytes);
    const result = await ffmpeg.exec([
      '-i', 'input', '-map', '0:v:0?', '-map', '0:a:0?',
      '-c:v', 'libx264', '-preset', 'ultrafast', '-crf', '22',
      '-vf', 'scale=trunc(iw/2)*2:trunc(ih/2)*2', '-pix_fmt', 'yuv420p',
      '-c:a', 'aac', '-b:a', '192k', '-movflags', '+faststart', 'output.mp4',
    ]);
    signal.throwIfAborted();
    if (result !== 0) throw new Error('conversion failed. the file may be damaged or use an unsupported codec.');
    const output = await ffmpeg.readFile('output.mp4');
    if (typeof output === 'string') throw new Error('conversion produced no media');
    return new Blob([new Uint8Array(output)], { type: 'video/mp4' });
  } finally {
    if (wasmURL) URL.revokeObjectURL(wasmURL);
    clearTimeout(timeout);
    signal.removeEventListener('abort', abort);
    ffmpeg.terminate();
  }
}
